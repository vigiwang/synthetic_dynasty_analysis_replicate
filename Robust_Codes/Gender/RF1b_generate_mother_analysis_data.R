  install_and_load <- function(pkg_list) {
    for (pkg in pkg_list) {
      if (!requireNamespace(pkg, quietly = TRUE)) {
        message("Installing missing package: ", pkg)
        install.packages(pkg, dependencies = TRUE)
      }
      library(pkg, character.only = TRUE)
    }
  }

  install_and_load(packages)
}


#-------------------------------------------------#
#     LOAD GSS DATA AND MOTHER-CHILD PAIRS
#-------------------------------------------------#

# Load GSS microdata (via the {gssr} package)
# Install from r-universe if not already available

if(HPC){
  gss_all <- read_dta(
    file.path(
      dir_root,
      "Data",
      "gss7224_r2.dta"
    )
  )

}else{
  if (!requireNamespace("gssr", quietly = TRUE)) {
    install.packages(
      "gssr",
      repos = c(
        "https://kjhealy.r-universe.dev",
        "https://cloud.r-project.org"
      )
    )
  }
  library(gssr)
  data(gss_all)
}


# Load the mother-child occupational pairs (5-class EGP):

gss_mc_occ10_5class <- readr::read_rds(
  file.path(
    dir_data,
    "gss_mc_occ10_5class.rds"
  )
)

#-------------------------------------------------#
#             ONLY KEEP MOTHER-SON PAIRS:
#-------------------------------------------------#

gss_ms_occ10_5class <-
  gss_mc_occ10_5class %>%
  left_join(
    gss_all %>%
      mutate(
        uniqid = row_number()
      ) %>%
      dplyr::select(
        uniqid,
        sex
      ),
    by = "uniqid"
  ) %>%
  filter(
    sex == 1
  )


#-------------------------------------------------#
#           ONLY KEEP MOTHER-DAUGHTER PAIRS:
#-------------------------------------------------#

gss_md_occ10_5class <-
  gss_mc_occ10_5class %>%
  left_join(
    gss_all %>%
      mutate(
        uniqid = row_number()
      ) %>%
      dplyr::select(
        uniqid,
        sex
      ),
    by = "uniqid"
  ) %>%
  filter(
    sex == 2
  )




#-----------------------------#
#  Save the Data:
#-----------------------------#

write_rds(
  gss_ms_occ10_5class,
  file.path(
    dir_data,
    "gss_ms_occ10_5class.rds")
)

write_rds(
  gss_md_occ10_5class,
  file.path(
    dir_data,
    "gss_md_occ10_5class.rds")
)


# Open log：
sink(log_path, split = TRUE)

