#-------------------------------------------------------------------------------
# U.S. Occupational Mobility — Replication Files
#
# Project:     U.S. Occupational Mobility Analysis
# Repository:  https://github.com/synthetic_dynasty_analysis_replicate
#
# Script:      RF1b_generate_mother_analysis_data.R
#
# Inputs:
#   - GSS microdata (via the {gssr} package): gssr::data(gss_all)
#   - GSS mother-child occupational pairs (5-class EGP):
#       Data/robustness_check/gss_mc_occ10_5class.rds
#
# Outputs:
#   - Log file:
#       code/_LOGS/Data/robustness_check_mother_log.txt
#   - Analytical dataset:
#       - Data/robustness_check/gss_ms_occ10_5class.rds
#       - Data/robustness_check/gss_md_occ10_5class.rds
#
# Description:
#   This script constructs the analytical samples for the gender robustness
#   check on the mother's side. It separates the mother-child occupational
#   pairs (generated by RE1_generate_gender_analysis_data.R) into
#   mother-son and mother-daughter pairs, following the same procedure used
#   to separate the father-child pairs into father-son and father-daughter
#   pairs.
#
# Notes:
#   - The GSS input is accessed programmatically through {gssr}. For exact
#     replication, ensure the installed {gssr} version (and its bundled GSS
#     release) matches the version used in the analysis.
#
#-------------------------------------------------------------------------------

#-------------------------------------------------#
#  INSTALL/LOAD DEPENDENCIES AND CMED R PACKAGE   #
#-------------------------------------------------#
if(HPC){
  .libPaths(c("/home/weiqiw/R/x86_64-pc-linux-gnu-library/4.4", .libPaths()))
  library("tidyverse")
  library("readr")
  library("haven")
  library("dplyr")
}else{
  packages <-
